"""Reproduce pinned SDK event log bodies and Go printable Unicode ranges."""
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SHA = '1dc92b73900fac74dc357a938e4b5eee6392b418'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    env = dict(os.environ, GOROOT=os.environ.get('GOROOT', '/usr/local/go'), GOTOOLCHAIN='local', GOTELEMETRY='off', GOWORK='off', GOFLAGS='-mod=readonly', TZ='UTC', GOPROXY='off', GOSUMDB='off')
    env.setdefault('GOCACHE', '/workspace/scratch/go-cache')
    env.setdefault('GOMODCACHE', '/workspace/scratch/go/pkg/mod')
    goroot = Path(env['GOROOT'])
    go = str(goroot / 'bin/go')
    version = subprocess.check_output([go, 'version'], env=env, text=True).strip()
    if not version.startswith('go version go1.26.8 '):
        raise SystemExit('This Unicode reference requires Go 1.26.8')
    with tempfile.TemporaryDirectory() as temp:
        source = Path(temp)
        archive = subprocess.check_output(['git', 'archive', SHA], cwd=ROOT / 'repos/sdk')
        with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
            tar.extractall(source, filter='data')
        paths = ['internal/agent/logger.go', 'internal/agent/items.go', 'internal/agent/event_stream.go', 'pkg/agentsdk/aliases.go', 'go.mod', 'go.sum']
        provenance = {'repository': 'https://github.com/gratefulagents/sdk', 'commit': SHA, 'license': 'GPL-3.0-only',
                      'goVersion': version,
                      'sourceSHA256': {p: hashlib.sha256((source / p).read_bytes()).hexdigest() for p in paths},
                      'stdlibSHA256': {p: hashlib.sha256((goroot / p).read_bytes()).hexdigest() for p in ['src/strconv/quote.go', 'src/strconv/isprint.go', 'src/unicode/tables.go', 'LICENSE']},
                      'harnessSHA256': {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in ['scripts/content-logger-reference/run.py', 'scripts/content-logger-reference/reference_test.go', 'scripts/content-logger-reference/agent_reference_test.go']}}
        shutil.copyfile(ROOT / 'scripts/content-logger-reference/reference_test.go', source / 'pkg/agentsdk/native_content_logger_test.go')
        shutil.copyfile(ROOT / 'scripts/content-logger-reference/agent_reference_test.go', source / 'pkg/agentsdk/native_agent_logger_test.go')
        env['METADATA_OUTPUT'] = str(source / 'observations.json')
        subprocess.run([go, 'test', '-count=1', '-v', '-run', '^TestNativeContentLoggerReference$', './pkg/agentsdk'], cwd=source, env=env, check=True)
        observed = json.loads((source / 'observations.json').read_text())
        ranges = observed.pop('printableRanges')
        table = '// Copyright 2013 The Go Authors. All rights reserved.\n// Derived from Go 1.26.8 strconv.IsPrint (Unicode 15.0.0).\n// BSD-3-Clause license: docs/migration/licenses/go-LICENSE.txt.\n// Generated by scripts/content-logger-reference/run.py.\n\n'
        table += 'pub(super) const PRINTABLE: &[(u32, u32)] = &[\n'
        table += ''.join(f'    (0x{low:x}, 0x{high:x}),\n' for low, high in ranges)
        table += '];\n'
        products = {'fixtures/content-logger/observations.json': json.dumps(dict(provenance=provenance, **observed), indent=2, sort_keys=True) + '\n',
                    'crates/adk/src/content_logger/printable.rs': table,
                    'docs/migration/licenses/go-LICENSE.txt': (goroot / 'LICENSE').read_text()}
        for path, text in products.items():
            destination = ROOT / path
            if args.check:
                if destination.read_text() != text:
                    raise SystemExit(f'Content logger reference differs: {path}')
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(text)
        print('Pinned content logger observations and printable ranges reproduced exactly' if args.check else 'Wrote content logger reference products')


if __name__ == '__main__':
    main()
